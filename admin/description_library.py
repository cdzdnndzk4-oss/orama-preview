AUDIENCES = {"γυναικείο": "όσες", "ανδρικό": "όσους", "unisex": "όσους"}


def compose_description(item, variant=0, existing=()):
    style, audience = item.get("style"), item.get("audience")
    detail = str(item.get("visual_note") or "").strip().rstrip(". ")
    if style not in OPENINGS or audience not in AUDIENCES:
        raise ValueError("Επίλεξε χαρακτήρα και κοινό για την περιγραφή")
    if not 8 <= len(detail.split()) <= 20 or "\n" in detail:
        raise ValueError("Γράψε μία επιβεβαιωμένη οπτική λεπτομέρεια σε πρόταση 8–20 λέξεων")
    if isinstance(variant, bool) or not isinstance(variant, int) or not 0 <= variant < 50:
        raise ValueError("Μη έγκυρη εναλλακτική περιγραφή")
    who = AUDIENCES[audience]
    seed = int.from_bytes(hashlib.sha256(str(item.get("id", "")).encode()).digest()[:4], "big")
    prior = [text for text in existing if text]
    seen = set(prior)
    best = None
    for offset in range(50):
        position = (seed + variant + offset) % 50
        opening = OPENINGS[style][position % 5].format(who=who)
        ending = ENDINGS[position // 5].format(who=who)
        description = f"{opening} {detail}. {ending}"
        if 35 <= len(description.split()) <= 60 and description not in seen:
            repeat_words = ("προσωπικ", "χαρακτήρ", "κομψ", "διακριτ", "σύγχρον", "θέλουν")
            repetition = sum(max(0, sum(stem in part.lower() for part in (opening, detail, ending)) - 1) for stem in repeat_words)
            score = 6 * sum(opening in previous for previous in prior) + 5 * sum(ending in previous for previous in prior) + 2 * repetition
            candidate = (score, offset, description)
            if best is None or candidate < best:
                best = candidate
    if best is not None:
        return best[2]
    raise ValueError("Δεν βρέθηκε κατάλληλη διαφορετική περιγραφή· άλλαξε τη συγκεκριμένη οπτική σημείωση")
